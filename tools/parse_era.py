def parse_era(era):
    if not era:
        return None
    s = era.strip()
    # 「約N万年前」「数百万年前」「約A万〜B万年前」→ 先史(旧石器)
    m = re.search(r'約?(\d+)万〜(\d+)万年前', s)
    if m: return (-int(m.group(1))*10000, -int(m.group(2))*10000)
    m = re.search(r'約?(\d+)万年前', s)
    if m: return (-int(m.group(1))*10000, None)
    m = re.search(r'約?(\d+)〜(\d+)万年前', s)
    if m: return (-int(m.group(1))*10000, -int(m.group(2))*10000)
    if '数百万年前' in s or '万年前' in s: return (-1000000, None)
    m = re.search(r'約?(\d+)万〜(\d+)万年前', s)
    if m: return (-int(m.group(1))*10000, -int(m.group(2))*10000)
    # 「N千年紀」
    m = re.search(r'前(\d+)千年紀', s)
    if m: c=int(m.group(1)); return (-(c*1000), -((c-1)*1000+1))
    # 「NNNN〜NN年代」「NNNN年代」
    m = re.search(r'(\d{4})〜(\d{2,4})年代', s)
    if m:
        a=int(m.group(1)); b=m.group(2)
        bb=int(b) if len(b)==4 else a//100*100+int(b)
        return (a, bb+9)
    m = re.search(r'(\d{4})年代', s)
    if m: a=int(m.group(1)); return (a, a+9)
    # 世紀(前も含む、範囲・後半/初頭は無視して世紀全体)
    m = re.search(r'前(\d+)〜(\d+)世紀', s)
    if m:
        a, b = int(m.group(1)), int(m.group(2)); return (-(a*100-99), -((b-1)*100))
    m = re.search(r'前(\d+)世紀', s)
    if m:
        c = int(m.group(1)); return (-(c*100-99), -((c-1)*100))
    m = re.search(r'(\d+)〜(\d+)世紀', s)
    if m:
        a, b = int(m.group(1)), int(m.group(2)); return ((a-1)*100+1, b*100)
    m = re.search(r'(\d+)世紀', s)
    if m:
        c = int(m.group(1)); return ((c-1)*100+1, c*100)
    # 年
    m = re.search(r'前(\d+)〜前?(\d+)年', s)
    if m: return (-int(m.group(1)), -int(m.group(2)))
    m = re.search(r'前(\d+)年', s)
    if m: return (-int(m.group(1)), None)
    m = re.search(r'(\d{3,4})〜(\d{3,4})年', s)
    if m: return (int(m.group(1)), int(m.group(2)))
    m = re.search(r'(\d{3,4})年', s)
    if m: return (int(m.group(1)), None)
    # 時代区分・王朝(「宋代〜」「古代〜中世」などは最初にマッチするキーを起点、〜の右側も探す)
    # 完全一致優先
    core = s.replace('〜', '').replace('以降', '').replace('以前', '').replace('前期', '').replace('後期', '').replace('後半', '').replace('前半', '').replace('初頭', '').replace('末', '').replace('頃', '')
    if core in PERIOD_WORDS:
        return PERIOD_WORDS[core]
    # 「A〜B」形式: A の開始と B の終了を組み合わせる
    if '〜' in s:
        parts = [p.strip() for p in s.split('〜') if p.strip()]
        rng = [PERIOD_WORDS.get(p) for p in parts if p in PERIOD_WORDS]
        if rng:
            lo = rng[0][0]
            hi = rng[-1][1]
            return (lo, hi)
    # 部分一致(長いキーから)
    for k in sorted(PERIOD_WORDS, key=len, reverse=True):
        if k in s:
            return PERIOD_WORDS[k]
    return None
